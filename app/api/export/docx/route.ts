import { NextResponse } from "next/server";
import { Document, Packer, Paragraph } from "docx";
import { getUserFromCookies } from "@/lib/auth";

export async function GET() {
  const userPayload = getUserFromCookies();
  if (!userPayload) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const doc = new Document({
    sections: [{
      children: [
        new Paragraph({ text: "QA Test Plan", heading: "Title" }),
        new Paragraph({ text: "This document was generated from the QA Management portal." }),
        new Paragraph({ text: `Generated by: ${userPayload.email}` }),
      ],
    }],
  });

  const buffer = await Packer.toBuffer(doc);

  return new NextResponse(buffer, {
    headers: {
      "Content-Type": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      "Content-Disposition": "attachment; filename=qa-test-plan.docx",
    },
  });
}
